fn gcrs_to_true_of_date_refactor_preserves_gcrs_to_itrs() {
    for (utc_fields, expected) in FRAME_GOLDEN {
        let ts = TimeScales::from_utc(
            utc_fields.0,
            utc_fields.1,
            utc_fields.2,
            utc_fields.3,
            utc_fields.4,
            utc_fields.5,
        )
        .expect("valid UTC");
        let got = gcrs_to_itrs_matrix(&ts).expect("valid matrix");
        assert_matrix_near("direct", &got, expected, 1.0e-12);

        let tod = gcrs_to_true_of_date_matrix(&ts).expect("valid true-of-date matrix");
        let gast = greenwich_apparent_sidereal_time_radians(&ts).expect("valid GAST");
        let rebuilt = inline_rxr(&rot_z(-gast), &tod);
        assert_matrix_near("rebuilt", &rebuilt, expected, 1.0e-12);
    }

    let ts = TimeScales::from_utc(2024, 1, 1, 0, 0, 0.0).expect("valid UTC");
    let unit = unit_from_radec(267.0545293733468, -23.96185179890772);
    let itrs = mat3_vec3_mul(&gcrs_to_itrs_matrix(&ts).expect("valid matrix"), &unit)
        .expect("GCRS to ITRS");
    let roundtrip = mat3_vec3_mul(&itrs_to_gcrs_matrix(&ts).expect("valid matrix"), &itrs)
        .expect("ITRS to GCRS");
    for i in 0..3 {
        assert!((roundtrip[i] - unit[i]).abs() < 1.0e-12);
    }
}

