fn assert_equatorial(
    case: &str,
    field: &str,
    actual: sidereon_core::astro::bodies::Equatorial,
    expected: GoldenEquatorial,
    max_arcsec: f64,
) {
    let sep = equatorial_sep_arcsec(actual, expected);
    assert!(sep < max_arcsec, "{case} {field} separation {sep} arcsec");
    assert_relative(
        case,
        field,
        actual.distance_km,
        expected.distance_km,
        1.0e-8,
    );
}

fn equatorial_sep_arcsec(
    actual: sidereon_core::astro::bodies::Equatorial,
    expected: GoldenEquatorial,
) -> f64 {
    let a = unit_from_radec(actual.right_ascension_deg, actual.declination_deg);
    let b = unit_from_radec(expected.ra_deg, expected.dec_deg);
    libm::acos(dot3(a, b).clamp(-1.0, 1.0)) * ARCSEC_PER_RADIAN
}

fn equatorial_sep_arcsec_between(
    a: sidereon_core::astro::bodies::Equatorial,
    b: sidereon_core::astro::bodies::Equatorial,
) -> f64 {
    let a = unit_from_radec(a.right_ascension_deg, a.declination_deg);
    let b = unit_from_radec(b.right_ascension_deg, b.declination_deg);
    libm::acos(dot3(a, b).clamp(-1.0, 1.0)) * ARCSEC_PER_RADIAN
}

fn assert_angle_arcsec(case: &str, field: &str, actual: f64, expected: f64, max_arcsec: f64) {
    let diff = angle_diff_deg(actual, expected).abs() * 3600.0;
    assert!(diff < max_arcsec, "{case} {field} diff {diff} arcsec");
}

fn assert_linear_arcsec(case: &str, field: &str, actual: f64, expected: f64, max_arcsec: f64) {
    let diff = (actual - expected).abs() * 3600.0;
    assert!(diff < max_arcsec, "{case} {field} diff {diff} arcsec");
}

fn assert_relative(case: &str, field: &str, actual: f64, expected: f64, max_rel: f64) {
    let rel = (actual - expected).abs() / expected.abs().max(1.0);
    assert!(rel < max_rel, "{case} {field} relative diff {rel}");
}

fn unit_from_radec(ra_deg: f64, dec_deg: f64) -> [f64; 3] {
    let ra = ra_deg.to_radians();
    let dec = dec_deg.to_radians();
    [
        libm::cos(dec) * libm::cos(ra),
        libm::cos(dec) * libm::sin(ra),
        libm::sin(dec),
    ]
}

fn angle_diff_deg(actual: f64, expected: f64) -> f64 {
    let diff = (actual - expected + 180.0).rem_euclid(360.0) - 180.0;
    if diff <= -180.0 {
        diff + 360.0
    } else {
        diff
    }
}

fn wrap_360(deg: f64) -> f64 {
    deg.rem_euclid(360.0)
}

fn rot_z(angle: f64) -> Mat3 {
    let c = libm::cos(angle);
    let s = libm::sin(angle);
    [[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]]
}

fn assert_matrix_near(label: &str, actual: &Mat3, expected: &Mat3, tolerance: f64) {
    for i in 0..3 {
        for j in 0..3 {
            assert!(
                (actual[i][j] - expected[i][j]).abs() < tolerance,
                "{label}[{i}][{j}] {} vs {}",
                actual[i][j],
                expected[i][j]
            );
        }
    }
}

fn aberration_estimate_arcsec(
    station: &GeodeticStationKm,
    time: UtcInstant,
    kernel: &Spk,
    direction: sidereon_core::astro::bodies::Equatorial,
) -> f64 {
    let ts = time.time_scales();
    let et = (ts.jd_tdb - J2000_JD) * SECONDS_PER_DAY;
    let (x, y, z) = geodetic_to_itrs(
        station.latitude_deg,
        station.longitude_deg,
        station.altitude_km,
    )
    .expect("station ITRS");
    let station_itrs = [x, y, z];
    let v_itrs = [
        -OMEGA_E_DOT_RAD_S * station_itrs[1],
        OMEGA_E_DOT_RAD_S * station_itrs[0],
        0.0,
    ];
    let v_geo = mat3_vec3_mul(
        &itrs_to_gcrs_matrix(&ts).expect("ITRS to GCRS matrix"),
        &v_itrs,
    )
    .expect("station velocity");
    let v_earth = spk_velocity(kernel, 399, 0, et);
    let beta = scale3(add3(v_earth, v_geo), 1.0 / C_KM_S);
    let p = unit_from_radec(direction.right_ascension_deg, direction.declination_deg);
    let beta_parallel = scale3(p, dot3(p, beta));
    norm3(sub3(beta, beta_parallel)) * ARCSEC_PER_RADIAN
}

fn spk_velocity(kernel: &Spk, target: i32, center: i32, et: f64) -> [f64; 3] {
    let state = kernel
        .spk_state(target, center, et)
        .expect("SPK state for velocity");
    if let Some(velocity) = state.velocity_km_s {
        return velocity;
    }
    let before = kernel
        .spk_state(target, center, et - 1.0)
        .expect("SPK state before")
        .position_km;
    let after = kernel
        .spk_state(target, center, et + 1.0)
        .expect("SPK state after")
        .position_km;
    scale3(sub3(after, before), 0.5)
}
