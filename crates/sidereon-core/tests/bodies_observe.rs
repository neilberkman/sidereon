#[test]
fn correction_toggles_have_expected_scales() {
    let kernel = observe_kernel();
    let station = station_greenwich();
    let time = UtcInstant::from_utc(2024, 1, 1, 0, 0, 0, 0).expect("valid UTC");

    let full = observe_spk_body(&station, time, &kernel, 4).expect("full observation");
    let no_aberration = observe(
        &station,
        time,
        Target::Spk {
            kernel: &kernel,
            naif_id: 4,
        },
        {
            let mut options = ObserveOptions::default();
            options.aberration = false;
            options
        },
    )
    .expect("observation without aberration");
    let shift = equatorial_sep_arcsec_between(full.apparent_icrs, no_aberration.apparent_icrs);
    let estimate = aberration_estimate_arcsec(&station, time, &kernel, no_aberration.apparent_icrs);
    assert!(shift > 1.0 && shift < 30.0, "aberration shift {shift}");
    assert!(
        (shift - estimate).abs() < 0.5,
        "aberration shift {shift} estimate {estimate}"
    );

    let conjunction_time = UtcInstant::from_utc(2023, 11, 18, 0, 0, 0, 0).expect("valid UTC");
    let with_deflection =
        observe_spk_body(&station, conjunction_time, &kernel, 4).expect("full conjunction");
    let without_deflection = observe(
        &station,
        conjunction_time,
        Target::Spk {
            kernel: &kernel,
            naif_id: 4,
        },
        {
            let mut options = ObserveOptions::default();
            options.deflection = false;
            options
        },
    )
    .expect("conjunction without deflection");
    let deflection_shift = equatorial_sep_arcsec_between(
        with_deflection.apparent_icrs,
        without_deflection.apparent_icrs,
    );
    let elongation = equatorial_sep_arcsec_between(
        without_deflection.apparent_icrs,
        observe_spk_body(&station, conjunction_time, &kernel, 10)
            .expect("sun SPK observation")
            .apparent_icrs,
    ) / ARCSEC_PER_RADIAN;
    let bound_arcsec = 4.0 * 132_712_440_041.939_38
        / (C_KM_S * C_KM_S * 149_597_870.700 * elongation)
        * ARCSEC_PER_RADIAN;
    assert!(
        deflection_shift > 0.01 && deflection_shift < bound_arcsec * 2.0,
        "deflection shift {deflection_shift}, bound {bound_arcsec}"
    );
}

