#[test]
fn epochs_outside_the_gfct_intervals_are_refused() {
    let field = IcgemGravityField::parse(SYNTHETIC_ICGEM2).expect("icgem2");
    // C20 is defined from 2000-01-01; C21 from 1990.
    let t = sidereon_core::astro::time::civil::j2000_seconds(1995, 6, 1, 0, 0, 0.0);
    assert_eq!(
        field.coefficient_at(2, 0, t),
        Err(IcgemError::EpochOutsideValidity {
            degree: 2,
            order: 0,
            epoch_tt_seconds: t
        })
    );
    assert!(field.coefficient_at(2, 1, t).expect("C21").is_some());
    let gravity = field.gravity(6, 6).expect("gravity");
    let error = gravity
        .body_fixed_acceleration_at_km_s2([7000.0, 0.0, 0.0], t)
        .expect_err("outside validity");
    assert!(error.to_string().contains("coefficient 2,0"), "{error}");
    // The end of the last interval is exclusive.
    let end = sidereon_core::astro::time::civil::j2000_seconds(2030, 1, 1, 0, 0, 0.0);
    assert!(gravity
        .body_fixed_acceleration_at_km_s2([7000.0, 0.0, 0.0], end)
        .is_err());
    assert!(gravity
        .body_fixed_acceleration_at_km_s2([7000.0, 0.0, 0.0], end - 1.0)
        .is_ok());
    // A time-variable model has no value without an epoch.
    assert!(gravity
        .body_fixed_acceleration_km_s2([7000.0, 0.0, 0.0])
        .is_err());
    assert!(gravity
        .body_fixed_potential_km2_s2([7000.0, 0.0, 0.0])
        .is_err());
    assert_eq!(
        field.coefficient_at(2, 0, f64::NAN),
        Err(IcgemError::NonFiniteEpoch)
    );
}

#[test]
fn tide_systems_are_recorded_and_converted() {
    let mean = SYNTHETIC_ICGEM1.replace("tide_free", "mean_tide");
    let field = IcgemGravityField::parse(&mean).expect("mean tide");
    assert_eq!(field.header().tide_system, Some(TideSystem::MeanTide));
    assert_eq!(
        field.gravity(5, 5).expect("gravity").tide_system(),
        TideSystem::MeanTide
    );

    let unknown = SYNTHETIC_ICGEM1.replace("tide_free", "unknown");
    let field = IcgemGravityField::parse(&unknown).expect("unknown tide");
    assert_eq!(field.header().tide_system, None);
    assert_eq!(
        field.gravity(5, 5).err(),
        Some(IcgemError::UnknownTideSystem)
    );
    let assumed = field
        .with_assumed_tide_system(TideSystem::ZeroTide)
        .expect("assumed");
    assert_eq!(
        assumed.gravity(5, 5).expect("gravity").tide_system(),
        TideSystem::ZeroTide
    );

    let stated = IcgemGravityField::parse(EGM96_D36).expect("EGM96");
    assert_eq!(
        stated
            .clone()
            .with_assumed_tide_system(TideSystem::ZeroTide)
            .err(),
        Some(IcgemError::TideSystemConflict {
            stated: TideSystem::TideFree,
            assumed: TideSystem::ZeroTide
        })
    );
    assert!(stated
        .clone()
        .with_assumed_tide_system(TideSystem::TideFree)
        .is_ok());

    // IERS Conventions (2010) Equation 6.14: a zero-tide C20 holds the
    // permanent deformation A0 H0 k20 = 4.4228e-8 * -0.31460 * 0.30190 that a
    // tide-free C20 does not; a mean-tide C20 also holds A0 H0.
    let free = stated.gravity(4, 4).expect("tide-free");
    let zero = stated
        .gravity_in_tide_system(4, 4, TideSystem::ZeroTide)
        .expect("zero-tide");
    let mean = stated
        .gravity_in_tide_system(4, 4, TideSystem::MeanTide)
        .expect("mean-tide");
    let c20 = |g: &SphericalHarmonicGravity| g.coefficient(2, 0).expect("C20").c;
    let deformation = 4.4228e-8 * -0.31460 * 0.30190;
    let potential = 4.4228e-8 * -0.31460;
    assert_eq!(c20(&zero), c20(&free) + deformation);
    assert_eq!(c20(&mean), c20(&free) + (deformation + potential));
    assert_eq!(zero.tide_system(), TideSystem::ZeroTide);
    assert_eq!(mean.tide_system(), TideSystem::MeanTide);
    for (degree, order) in [(2, 1), (2, 2), (3, 0), (4, 4)] {
        assert_eq!(
            zero.coefficient(degree, order),
            free.coefficient(degree, order)
        );
    }
}

