#![cfg(sidereon_repo_tests)]
//! ICGEM gravity field reader against Orekit 13.1.10.
//!
//! The oracle, `fixtures/icgem/icgem_orekit.json`, is printed by
//! `fixtures-generators/icgem_orekit_oracle/generate.sh`: Orekit's
//! `ICGEMFormatReader` reads each file and `HolmesFeatherstoneAttractionModel`
//! (Holmes and Featherstone, 2002, Journal of Geodesy 76:279-299) evaluates the
//! body-fixed gradient and non-central potential at the same truncation. The
//! format is C. Förste, F. Barthelmes and E. S. Ince, "The ICGEM-format",
//! GFZ, 16 February 2023.
//!
//! Fixture fields (`fixtures/icgem`, written by `make_fields.py` beside the
//! generator): `egm96_d36.gfc` is EGM96 (Lemoine et al., 1998,
//! NASA/TP-1998-206861; NASA and NIMA, public domain) through degree 36, the
//! same values as the crate's embedded table. `unnormalized_d8.gfc` is EGM96
//! through degree 8 written unnormalized. `synthetic_icgem2.gfc` and
//! `synthetic_icgem1.gfc` hold EGM96 static values with synthetic
//! time-variable records exercising every record type; they describe no
//! published model. The degree 2190 field is synthetic, generated by the
//! integer formula below in both the generator and this test.

