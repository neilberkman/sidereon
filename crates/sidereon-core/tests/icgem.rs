/// SplitMix64 finalizer, as `IcgemOracle.mix`.
fn mix(seed: u64) -> u64 {
    let mut z = seed.wrapping_add(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^ (z >> 31)
}

/// Coefficient text of the synthetic degree 2190 field, as
/// `IcgemOracle.syntheticValue`.
fn synthetic_value(n: u64, m: u64, which: u64) -> String {
    if which == 1 && m == 0 {
        return "0.0".to_string();
    }
    if n == 2 && m == 0 {
        return "-0.484165371736E-03".to_string();
    }
    let mantissa = (mix((n << 32) | (m << 1) | which) % 2_000_001) as i64 - 1_000_000;
    let digits = (n * n).to_string().len() as i64;
    format!("{mantissa}e{}", -(10 + digits))
}

fn synthetic_d2190() -> &'static str {
    static TEXT: OnceLock<String> = OnceLock::new();
    TEXT.get_or_init(|| {
        let mut text = String::with_capacity(64 * 2_400_000);
        text.push_str(
            "product_type gravity_field\nmodelname SYNTHETIC_D2190\n\
             earth_gravity_constant 0.3986004415E+15\nradius 0.6378136300E+07\n\
             max_degree 2190\nerrors no\ntide_system tide_free\nend_of_head\n\
             gfc 0 0 1.0 0.0\ngfc 1 0 0.0 0.0\ngfc 1 1 0.0 0.0\n",
        );
        for n in 2..=2190_u64 {
            for m in 0..=n {
                text.push_str(&format!(
                    "gfc {n} {m} {} {}\n",
                    synthetic_value(n, m, 0),
                    synthetic_value(n, m, 1)
                ));
            }
        }
        text
    })
}

fn oracle() -> &'static Value {
    static ORACLE_JSON: OnceLock<Value> = OnceLock::new();
    ORACLE_JSON.get_or_init(|| serde_json::from_str(ORACLE).expect("oracle JSON"))
}

fn case(name: &str) -> &'static Value {
    oracle()["cases"]
        .as_array()
        .expect("cases")
        .iter()
        .find(|case| case["name"] == name)
        .unwrap_or_else(|| panic!("case {name}"))
}

fn f(value: &Value) -> f64 {
    value.as_f64().expect("number")
}

fn vec3(value: &Value) -> [f64; 3] {
    [f(&value[0]), f(&value[1]), f(&value[2])]
}

/// `|actual - expected| <= ulps * eps * |expected|`.
fn close_ulps(actual: f64, expected: f64, ulps: f64) -> bool {
    (actual - expected).abs() <= ulps * f64::EPSILON * expected.abs()
}

fn norm(v: [f64; 3]) -> f64 {
    (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt()
}

/// Largest disagreements of one case.
#[derive(Debug, Default)]
struct Disagreement {
    /// `|a - a_orekit| / |a_orekit|`.
    acceleration: f64,
    /// `|V - V_orekit| / |V_orekit|`.
    potential: f64,
}

fn case_truncation(case: &Value) -> (u16, u16) {
    (
        case["degree"].as_u64().expect("degree") as u16,
        case["order"].as_u64().expect("order") as u16,
    )
}

/// Largest disagreements of `gravity` with the case's Orekit samples.
fn compare_samples(case: &Value, gravity: &SphericalHarmonicGravity) -> Disagreement {
    let mut worst = Disagreement::default();
    for sample in case["samples"].as_array().expect("samples") {
        let epoch = f(&sample["epoch_tt_s"]);
        let position_m = vec3(&sample["position_m"]);
        let position_km = position_m.map(|x| x / 1000.0);
        let expected = vec3(&sample["acceleration_m_s2"]).map(|a| a / 1000.0);
        let actual = gravity
            .body_fixed_acceleration_at_km_s2(position_km, epoch)
            .expect("acceleration");
        let diff = [
            actual[0] - expected[0],
            actual[1] - expected[1],
            actual[2] - expected[2],
        ];
        worst.acceleration = worst.acceleration.max(norm(diff) / norm(expected));
        let expected_potential = f(&sample["potential_m2_s2"]) / 1.0e6;
        let potential = gravity
            .body_fixed_potential_at_km2_s2(position_km, epoch)
            .expect("potential");
        worst.potential = worst
            .potential
            .max((potential - expected_potential).abs() / expected_potential.abs());
    }
    worst
}

fn compare_case(name: &str, field: &IcgemGravityField) -> Disagreement {
    let case = case(name);
    let (degree, order) = case_truncation(case);
    let gravity = field.gravity(degree, order).expect("gravity");
    let worst = compare_samples(case, &gravity);
    for row in case["coefficients"].as_array().expect("coefficients") {
        let epoch = f(&row["epoch_tt_s"]);
        let n = row["degree"].as_u64().expect("degree") as u16;
        let m = row["order"].as_u64().expect("order") as u16;
        let from_field = field
            .coefficient_at(n, m, epoch)
            .expect("field")
            .expect("stored");
        let from_gravity = gravity
            .coefficient_at(n, m, epoch)
            .expect("gravity")
            .expect("inside");
        // Both paths share one evaluation.
        assert_eq!(from_field, from_gravity, "{name} {n},{m} at {epoch}");
        // Orekit forms base + trend * dt, then the cosine and the sine terms,
        // with the same angular rate 2 pi / (period * 365.25 d): the values
        // agree to the bit.
        assert_eq!(
            [from_field.c.to_bits(), from_field.s.to_bits()],
            [f(&row["c"]).to_bits(), f(&row["s"]).to_bits()],
            "{name} {n},{m} at {epoch}"
        );
    }
    worst
}

/// Tolerances on `|a - a_orekit| / |a_orekit|` and `|V - V_orekit| /
/// |V_orekit|`. Orekit sums the same Holmes and Featherstone recursion but
/// forms the gradient in spherical coordinates and converts it with
/// `1/sin(colatitude)`, where this crate forms it in Cartesian coordinates, so
/// the sums round differently. The difference grows with the number of terms
/// that contribute.
struct Tolerance {
    acceleration: f64,
    potential: f64,
}

/// Degree 36 and below: largest measured 1.0e-15 (acceleration, unnormalized
/// EGM96 at LEO) and 7.3e-16 (potential), a few units in the last place of
/// a sum of at most 700 terms.
const LOW_DEGREE: Tolerance = Tolerance {
    acceleration: 2.0e-15,
    potential: 2.0e-15,
};

/// Degree 360: largest measured 3.4e-15 at 800 km and latitude -72.5 deg, where
/// terms through degree 360 still contribute; potential 9.0e-16.
const DEGREE_360: Tolerance = Tolerance {
    acceleration: 6.0e-15,
    potential: 2.0e-15,
};

/// Degree 2190: largest measured 8.6e-15 on the Earth's surface at 6371 km,
/// inside the reference sphere, where `(a/r)^n` stays near 1 and all 2.4
/// million terms of the synthetic Kaula-rule field contribute; 3.4e-15 or less
/// at every satellite altitude. Potential 1.4e-15.
const DEGREE_2190: Tolerance = Tolerance {
    acceleration: 1.6e-14,
    potential: 3.0e-15,
};

fn assert_within(name: &str, worst: &Disagreement, tolerance: &Tolerance) {
    assert!(
        worst.acceleration <= tolerance.acceleration,
        "{name}: acceleration {worst:?}"
    );
    assert!(
        worst.potential <= tolerance.potential,
        "{name}: potential {worst:?}"
    );
}

fn assert_case(name: &str, field: &IcgemGravityField, tolerance: &Tolerance) {
    assert_within(name, &compare_case(name, field), tolerance);
}

const EGM96_CASES: [&str; 4] = ["egm96_d36", "egm96_d36_o20", "egm96_d12", "egm96_zonal_d8"];

