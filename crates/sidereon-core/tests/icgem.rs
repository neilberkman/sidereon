/// Max degree 2 `icgem2.0` field, no sigmas, with `C20` given by one gfct
/// record over 2000-01-01 to 2030-01-01 and `extra` appended.
fn icgem2_c20_field(extra: &str) -> String {
    format!(
        "product_type gravity_field\nmodelname T\nearth_gravity_constant 3.986004415e14\n\
         radius 6378136.3\nmax_degree 2\nerrors no\nformat icgem2.0\ntide_system tide_free\n\
         end_of_head\ngfct 2 0 -4.8e-4 0.0 20000101.0000 20300101.0000\n\
         gfc 2 1 0.0 0.0\ngfc 2 2 2.4e-6 -1.4e-6\n{extra}"
    )
}

/// 2000-01-01 00:00 TT, seconds from J2000.
const T2000: f64 = -43_200.0;

#[test]
fn periods_too_short_for_a_finite_phase_are_typed_errors() {
    let text = icgem2_c20_field("acos 2 0 1.0e-11 0.0 20000101.0000 20300101.0000 1e-320\n");
    let field = IcgemGravityField::parse(&text).expect("parse");
    // At the record's epoch the phase is zero, so the value is exact.
    let at_t0 = field.coefficient_at(2, 0, T2000).expect("t0").expect("C20");
    assert_eq!(at_t0.c, -4.8e-4 + 1.0e-11);
    assert_eq!(at_t0.s, 0.0);
    // One second later 2 pi / (1e-320 y) * 1 s overflows the phase.
    assert_eq!(
        field.coefficient_at(2, 0, T2000 + 1.0),
        Err(IcgemError::NonFiniteCoefficient {
            degree: 2,
            order: 0,
            epoch_tt_seconds: T2000 + 1.0
        })
    );
    let gravity = field.gravity(2, 2).expect("gravity");
    assert_eq!(
        gravity
            .coefficient_at(2, 0, T2000)
            .expect("t0")
            .expect("C20")
            .c,
        -4.8e-4 + 1.0e-11
    );
    assert!(matches!(
        gravity.coefficient_at(2, 0, T2000 + 1.0),
        Err(PropagationError::InvalidInput(_))
    ));
    assert!(matches!(
        gravity.body_fixed_acceleration_at_km_s2([7000.0, 0.0, 0.0], T2000 + 1.0),
        Err(PropagationError::InvalidInput(_))
    ));

    // A zero amplitude contributes zero at any phase.
    let text = icgem2_c20_field("acos 2 0 0.0 0.0 20000101.0000 20300101.0000 1e-320\n");
    let field = IcgemGravityField::parse(&text).expect("parse");
    let later = field
        .coefficient_at(2, 0, T2000 + 1.0)
        .expect("value")
        .expect("C20");
    assert_eq!((later.c, later.s), (-4.8e-4, 0.0));
}

#[test]
